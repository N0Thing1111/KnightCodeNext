create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id, role, student_id, username, name, email, class_section)
  values(new.id, case when new.raw_user_meta_data->>'role' in ('student','teacher','admin') then (new.raw_user_meta_data->>'role')::public.account_role else 'student' end, nullif(new.raw_user_meta_data->>'student_id',''), nullif(lower(new.raw_user_meta_data->>'username'),''), coalesce(nullif(new.raw_user_meta_data->>'name',''), split_part(new.email,'@',1)), lower(new.email), nullif(new.raw_user_meta_data->>'class_section',''));
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

create or replace function public.handle_user_email_change() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.email is distinct from old.email then
    update public.profiles set email=lower(new.email) where id=new.id;
  end if;
  return new;
end $$;
create trigger on_auth_user_email_changed after update of email on auth.users for each row execute function public.handle_user_email_change();

