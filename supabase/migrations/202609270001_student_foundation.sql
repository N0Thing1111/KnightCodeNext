create table public.student_level_sessions (
  id bigint generated always as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  level_id bigint not null references public.levels(id) on delete cascade,
  run_id text not null,
  session_number integer not null default 1,
  base_attempts integer not null default 0,
  base_mistakes integer not null default 0,
  base_seconds integer not null default 0,
  base_lines integer not null default 0,
  attempts integer not null default 0,
  mistakes integer not null default 0,
  play_time_seconds integer not null default 0,
  lines_used integer not null default 0,
  completed_lines integer,
  completed boolean not null default false,
  telemetry_version integer not null default 2,
  partial_history boolean not null default false,
  code_mode public.code_mode,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (student_id, level_id, run_id, session_number)
);

