-- KnightCode V2 student foundation (PostgreSQL + Supabase Auth + RLS)
create extension if not exists pgcrypto;

create type public.account_role as enum ('student','teacher','admin');
create type public.theme_name as enum ('dark','light');
create type public.class_status as enum ('active','archived');
create type public.code_mode as enum ('guided','hint','free');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role public.account_role not null default 'student',
  student_id text unique,
  username text unique,
  name text not null check (char_length(name) between 1 and 150),
  email text not null unique,
  class_section text,
  avatar_key text not null default 'knight' check (avatar_key in ('knight','blue','mage','fox','dragon','robot')),
  profile_image text,
  theme_preference public.theme_name not null default 'dark',
  total_xp integer not null default 0 check (total_xp >= 0),
  current_streak integer not null default 0 check (current_streak >= 0),
  longest_streak integer not null default 0 check (longest_streak >= 0),
  last_activity_date date,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.lessons (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  learning_objective text not null default '',
  content text not null default '',
  order_number integer not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.levels (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  level_number integer not null unique,
  order_in_lesson integer not null,
  title text not null,
  description text not null default '',
  difficulty text not null default 'Beginner',
  xp_reward integer not null default 100 check (xp_reward >= 0),
  active boolean not null default true,
  starter_code_enabled boolean not null default false,
  starter_code_template text not null default '',
  starter_code_locked boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (lesson_id, order_in_lesson)
);

create table public.classes (
  id bigint generated by default as identity primary key,
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,
  section text not null,
  subject text not null default 'Programming',
  school_year text,
  description text,
  status public.class_status not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.class_students (
  class_id bigint not null references public.classes(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (class_id, student_id)
);

create table public.assignments (
  id bigint generated by default as identity primary key,
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  class_id bigint references public.classes(id) on delete cascade,
  student_id uuid references public.profiles(id) on delete cascade,
  lesson_id bigint references public.lessons(id) on delete cascade,
  level_id bigint references public.levels(id) on delete cascade,
  title text not null,
  instructions text,
  due_date timestamptz,
  created_at timestamptz not null default now(),
  check (class_id is not null or student_id is not null),
  check (lesson_id is not null or level_id is not null)
);

create table public.student_level_progress (
  student_id uuid not null references public.profiles(id) on delete cascade,
  level_id bigint not null references public.levels(id) on delete cascade,
  completed boolean not null default false,
  attempts integer not null default 0 check (attempts >= 0),
  mistakes integer not null default 0 check (mistakes >= 0),
  play_time_seconds integer not null default 0 check (play_time_seconds >= 0),
  lines_used integer check (lines_used >= 0),
  best_time_seconds integer check (best_time_seconds >= 0),
  best_lines_used integer check (best_lines_used >= 0),
  xp_earned integer not null default 0 check (xp_earned >= 0),
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (student_id, level_id)
);

create table public.student_activity (
  id bigint generated always as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  level_id bigint references public.levels(id) on delete cascade,
  action_type text not null,
  xp_earned integer not null default 0,
  duration_seconds integer not null default 0,
  metadata jsonb,
  created_at timestamptz not null default now()
);

create table public.achievements (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text not null,
  icon text not null default '✦',
  requirement_type text not null,
  requirement_value integer not null default 1
);

create table public.student_achievements (
  student_id uuid not null references public.profiles(id) on delete cascade,
  achievement_id bigint not null references public.achievements(id) on delete cascade,
  earned_at timestamptz not null default now(),
  primary key (student_id, achievement_id)
);

create table public.student_notifications (
  id bigint generated always as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  notification_key text,
  type text not null default 'activity',
  title text not null,
  message text not null,
  link text,
  is_read boolean not null default false,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  unique (student_id, notification_key)
);

create table public.student_telemetry_runs (
  student_id uuid not null references public.profiles(id) on delete cascade,
  level_id bigint not null references public.levels(id) on delete cascade,
  run_id text not null,
  sequence_number integer not null default 0,
  attempts integer not null default 0,
  mistakes integer not null default 0,
  total_seconds integer not null default 0,
  total_lines integer not null default 0,
